	public static Mesh CreateQuad(Vector2 minUV, Vector2 maxUV)
	{
		Mesh mesh = new Mesh();
		Vector2 vector = minUV;
		string text = vector.ToString();
		vector = maxUV;
		mesh.name = "Quad " + text + " " + vector.ToString();
		mesh.vertices = new Vector3[4]
		{
			new Vector3(-1f, -1f, 0f),
			new Vector3(-1f, 1f, 0f),
			new Vector3(1f, 1f, 0f),
			new Vector3(1f, -1f, 0f)
		};
		mesh.uv = new Vector2[4]
		{
			new Vector2(minUV.x, minUV.y),
			new Vector2(minUV.x, maxUV.y),
			new Vector2(maxUV.x, maxUV.y),
			new Vector2(maxUV.x, minUV.y)
		};
		mesh.triangles = new int[6] { 0, 3, 2, 0, 2, 1 };
		mesh.normals = new Vector3[4]
		{
			new Vector3(0f, 0f, 1f),
			new Vector3(0f, 0f, 1f),
			new Vector3(0f, 0f, 1f),
			new Vector3(0f, 0f, 1f)
		};
		mesh.tangents = new Vector4[4]
		{
			new Vector4(1f, 0f, 0f, 1f),
			new Vector4(1f, 0f, 0f, 1f),
			new Vector4(1f, 0f, 0f, 1f),
			new Vector4(1f, 0f, 0f, 1f)
		};
		return mesh;
	}
